import {createRequire} from 'node:module';
import {readFileSync,writeFileSync,mkdirSync,cpSync,existsSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=resolve(fileURLToPath(new URL('../../../',import.meta.url)));
const here=fileURLToPath(new URL('.',import.meta.url));
const web=join(root,'src/cyrene/workbench/webui');
const require=createRequire(join(web,'package.json'));
const esbuild=require('esbuild');
const output=process.argv[2];
if(!output||(existsSync(output)&&!process.argv.includes('--rebuild')))throw Error('Supply a new output directory');
mkdirSync(output,{recursive:true});
if(!existsSync(join(output,'frontend')))cpSync(join(web,'frontend'),join(output,'frontend'),{recursive:true});
const source=readFileSync(join(output,'frontend/features/chat/runtime-timeline.jsx'),'utf8');
const manifest=JSON.parse(readFileSync(join(here,'guarded-merge-source.json'),'utf8'));
if(createHash('sha256').update(source).digest('hex')!==manifest.source_sha256)throw Error('Candidate is stale; do not test a mismatched source');
const candidate=readFileSync(join(here,'proposed-runtime-timeline.jsx'),'utf8');
const sourceHashes={};
const entry=join(output,'entry.jsx');
writeFileSync(entry,`import React from 'react'; import * as ReactDOM from 'react-dom/client';
window.React=React; window.__auditFastHits=0;
const fixtureStorage=new Map(); Object.defineProperty(window,'localStorage',{value:{getItem:key=>fixtureStorage.get(String(key))??null,setItem:(key,value)=>fixtureStorage.set(String(key),String(value)),removeItem:key=>fixtureStorage.delete(String(key)),clear:()=>fixtureStorage.clear()},configurable:true});
const NativeDate=Date; window.Date=class extends NativeDate {constructor(...args){super(...(args.length?args:['2026-09-20T12:00:00Z']));}static now(){return NativeDate.parse('2026-09-20T12:00:00Z');}};
window.addEventListener('error',e=>parent.postMessage({kind:'audit-error',variant:__AUDIT_VARIANT__,message:e.message},location.origin));
await import('./frontend/platform/runtime.jsx');
await import('./frontend/platform/events.jsx');
await import('./frontend/platform/api.jsx');
await import('./frontend/workbench-i18n.jsx');
await import('./frontend/shared/markdown/renderer.jsx');
window.CyreneUI.register('model',{isPermissionQuestionKind:kind=>String(kind).includes('permission')});
window.CyreneUI.register('browser',{Icon:null});
window.CyreneUI.register('data',{state:{pluginModules:[],settings:{}},useVersion:()=>0});
window.CyreneUI.register('shortcuts',{hint:()=>'',label:()=>'',getShortcut:()=>'',matches:()=>false});
window.CyreneUI.register('feedback',{showToast:()=>{},dismissToast:()=>{}});
window.CyreneUI.register('format',{relativeTime:()=>'',formatBytes:n=>String(n)});
const {AuditApp}=await import('./audit-app.jsx');
ReactDOM.createRoot(document.getElementById('app')).render(<AuditApp/>);
`);
cpSync(join(here,'full_audit_app.jsx'),join(output,'audit-app.jsx'));
for(const variant of ['baseline','candidate']){
  await esbuild.build({entryPoints:[entry],outfile:join(output,variant+'.js'),bundle:true,format:'esm',platform:'browser',target:'chrome120',jsx:'transform',nodePaths:[join(web,'node_modules')],define:{__AUDIT_VARIANT__:JSON.stringify(variant),'process.env.NODE_ENV':'"production"'},loader:{'.woff2':'dataurl','.woff':'dataurl','.svg':'dataurl'},plugins:[{name:'isolated-snapshot',setup(build){build.onLoad({filter:/\.(jsx|mjs)$/},args=>{
    if(!args.path.startsWith(join(output,'frontend')))return;
    let contents=readFileSync(args.path,'utf8');
    sourceHashes[args.path.slice(output.length)]=createHash('sha256').update(contents).digest('hex');
    if(args.path.endsWith('/features/chat/runtime-timeline.jsx')&&variant==='candidate')contents=candidate.replace('var ordered = wbcTryMergeOrderedMessages(messages, additions);','var ordered = wbcTryMergeOrderedMessages(messages, additions); window.__auditFastHits += ordered === null ? 0 : 1;');
    if(args.path.endsWith('/features/chat/conversation.jsx'))contents+='\nexport {WbcConversationMessages};';
    return {contents,loader:'jsx'};
  });}}]});
  const css=Array.from(readFileSync(join(output,'frontend/index.html'),'utf8').matchAll(/<link rel="stylesheet" href="([^"?]+)[^"]*"/g),m=>m[1]).filter(p=>existsSync(join(output,'frontend',p))).map(p=>`<link rel="stylesheet" href="/frontend/${p}">`).join('');
  writeFileSync(join(output,variant+'.html'),`<!doctype html><html data-theme="light"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Cyrene ${variant} fixture</title>${css}<style>html,body{margin:0;height:100%;overflow:auto}.workbench-shell,.wbc-page,#app{height:100vh;width:100%;}.audit-thread{height:100vh;display:flex;position:relative;background:var(--wb-main-bg);color:var(--wb-text)}.audit-thread > .wbc-main{flex:1;min-width:0;}.audit-split-wrapper{width:50%;height:100%;position:relative;}.audit-split-wrapper > aside{height:100%;width:100%;}#actions{position:fixed;bottom:0;right:0;background:white;color:black;font-size:10px;z-index:9999}</style><script src="/vendor/marked.min.js"></script><script src="/vendor/purify.min.js"></script><div id="app"></div><script type="module" src="/${variant}.js"></script></html>`);
}
mkdirSync(join(output,'vendor'),{recursive:true});
for(const name of ['marked.min.js','purify.min.js'])cpSync(join(web,'static/app',name),join(output,'vendor',name));
cpSync(join(here,'full_audit_parent.html'),join(output,'index.html'));
writeFileSync(join(here,'full-audit-source-manifest.json'),JSON.stringify({baseline:manifest.source_sha256,candidate:manifest.candidate_sha256,sourceHashes,output},null,2)+'\n');
console.log(output);
